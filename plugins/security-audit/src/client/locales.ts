/**
 * Pick the plural pair one count selects.
 * @param base - the key without its `.one` or `.other` suffix.
 * @param count - the count the copy names.
 * @returns the key to translate.
 */
export function pluralKey<Base extends string>(base: Base, count: number): `${Base}.one` | `${Base}.other` {
  return count === 1 ? `${base}.one` : `${base}.other`
}
